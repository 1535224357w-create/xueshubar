def run():
    with app.app_context():
        added = 0
        for parent_name, sub_topics in SUB_TOPICS.items():
            parent = KnowledgePoint.query.filter_by(name=parent_name).first()
            if not parent:
                print(f'[跳过] 未找到: {parent_name}')
                continue
            existing = {c.name for c in parent.children.all()}
            for st in sub_topics:
                if st not in existing:
                    db.session.add(KnowledgePoint(name=st, parent_id=parent.id))
                    added += 1

        db.session.commit()
        print(f'新增 {added} 个子知识点')

        # 打印结构
        for root in KnowledgePoint.query.filter_by(parent_id=None).order_by(KnowledgePoint.name).all():
            print(f'\n■ {root.name}')
            for c2 in root.children.order_by(KnowledgePoint.name).all():
                subs = list(c2.children.order_by(KnowledgePoint.name).all())
                print(f'  ├─ {c2.name}')
                for c3 in subs:
                    print(f'  │   └─ {c3.name}')
                if not subs:
                    print(f'  │   (无子知识点)')


if __name__ == '__main__':
    run()
